//! Retained Cargo build-script trees selected from a coherent source snapshot.
//!
//! This projects an already approved generated root; it never opens OUT_DIR or
//! runs a build script. The caller binds Cargo's observed output record and this
//! complete generated inventory to the action key before remote admission.

use crate::snapshot_capture::{MemberKind, SealedSourceSnapshot};
use crate::source_transfer::{MAX_SOURCE_FILES, SourceFile, SourceManifest};
use sha2::{Digest, Sha256};
use std::collections::BTreeSet;
use std::io;
use std::sync::Arc;

/// Maximum number of explicitly retained generated subdirectories, excluding
/// the root. Directories consume request space even when they contain no files.
pub const MAX_GENERATED_DIRECTORIES: usize = 4096;

fn invalid(message: &'static str) -> io::Error {
    io::Error::new(io::ErrorKind::InvalidData, message)
}

/// Validate the complete relative directory inventory of one generated tree.
/// The root is implicit. Every other parent must appear before its descendants
/// in the strictly sorted inventory; aliases and traversal are never normalized
/// into permission to create a different path.
///
/// # Errors
/// Unsafe, duplicate, unsorted, oversized or parentless directory inventories.
pub fn validate_generated_directories(directories: &[String]) -> io::Result<()> {
    if directories.len() > MAX_GENERATED_DIRECTORIES
        || directories.windows(2).any(|pair| pair[0] >= pair[1])
    {
        return Err(invalid(
            "generated directory inventory is unbounded or not sorted and unique",
        ));
    }
    for path in directories {
        if path.len() > 1024
            || path.contains(['\\', ':'])
            || path.chars().any(char::is_control)
            || path.split('/').count() > 32
            || path
                .split('/')
                .any(|part| part.is_empty() || matches!(part, "." | ".."))
        {
            return Err(invalid(
                "generated directory path is not normalized and relative",
            ));
        }
        if let Some((parent, _)) = path.rsplit_once('/')
            && directories
                .binary_search_by(|candidate| candidate.as_str().cmp(parent))
                .is_err()
        {
            return Err(invalid("generated directory inventory omits a parent"));
        }
    }
    Ok(())
}

/// Exact generated bytes and modes retained in the same image as their package.
/// An empty selection still owns a real captured root. Its mount is selected by
/// the execution context; no invented sentinel file is added to the manifest.
#[derive(Debug, Clone)]
pub struct GeneratedSource {
    image: Arc<SealedSourceSnapshot>,
    root: String,
    files: Vec<SourceFile>,
    directories: Vec<String>,
}

impl GeneratedSource {
    /// Select every regular member of an already approved generated root.
    /// Missing members, aliases and nonregular inputs refuse the entire bundle.
    /// Combining this with package source requires the same capture owner, not
    /// two independently captured trees that merely have matching digests.
    pub fn from_snapshot(
        image: Arc<SealedSourceSnapshot>,
        root: &str,
        paths: &[String],
    ) -> io::Result<Self> {
        if paths.len() > MAX_SOURCE_FILES {
            return Err(invalid("generated source exceeds the file count bound"));
        }
        let captured = image
            .manifest(root)
            .ok_or_else(|| invalid("generated source root was not captured"))?;
        let mut expected = BTreeSet::new();
        let mut directories = Vec::new();
        for (path, member) in &captured.members {
            match member {
                MemberKind::Regular { .. } => {
                    expected.insert(path.as_str());
                }
                MemberKind::Directory => directories.push(path.clone()),
                MemberKind::Symlink { .. } => {
                    return Err(invalid("generated source contains a symlink"));
                }
            }
        }
        let selected: BTreeSet<_> = paths.iter().map(String::as_str).collect();
        if selected.len() != paths.len() || selected != expected {
            return Err(invalid(
                "generated source selection is not its complete captured inventory",
            ));
        }
        // The byte transport still contains files only. The dependency context
        // carries this separate complete directory inventory, and the worker
        // reconstructs one private tree without modifying its sealed bundle.
        validate_generated_directories(&directories)?;
        for path in &selected {
            for (offset, _) in path.match_indices('/') {
                if directories
                    .binary_search_by(|candidate| candidate.as_str().cmp(&path[..offset]))
                    .is_err()
                {
                    return Err(invalid("generated file has an uncaptured parent directory"));
                }
            }
        }
        let mut files = Vec::with_capacity(paths.len());
        for path in selected {
            let Some(MemberKind::Regular {
                size,
                content_sha256,
                mode,
                ..
            }) = captured.members.get(path)
            else {
                return Err(invalid("generated source member is not regular"));
            };
            let bytes = image
                .file_bytes(root, path)
                .ok_or_else(|| invalid("generated source bytes were not retained"))?;
            if bytes.len() as u64 != *size
                || <[u8; 32]>::from(Sha256::digest(bytes)) != *content_sha256
            {
                return Err(invalid(
                    "generated source bytes differ from the captured manifest",
                ));
            }
            files.push(SourceFile {
                path: format!("generated/{path}"),
                len: *size,
                sha256: *content_sha256,
                executable: mode & 0o111 != 0,
            });
        }
        // The combined package/generated/dependency manifest enforces aggregate
        // limits too. Validate projected names here without inventing a file for
        // the supported empty generated tree.
        if !files.is_empty() {
            SourceManifest::new(files.clone())?;
        }
        Ok(Self {
            image,
            root: root.to_owned(),
            files,
            directories,
        })
    }

    #[must_use]
    pub fn shares_snapshot(&self, image: &Arc<SealedSourceSnapshot>) -> bool {
        Arc::ptr_eq(&self.image, image)
    }

    #[must_use]
    pub fn files(&self) -> &[SourceFile] {
        &self.files
    }

    /// Complete sorted generated subdirectory inventory, including empty
    /// directories. The captured root itself is represented by the context.
    #[must_use]
    pub fn directories(&self) -> &[String] {
        &self.directories
    }

    /// Only declared wire paths can select bytes; a prefix alone grants nothing.
    #[must_use]
    pub fn file_bytes(&self, path: &str) -> Option<&[u8]> {
        self.files
            .binary_search_by(|file| file.path.as_str().cmp(path))
            .ok()?;
        self.image
            .file_bytes(&self.root, path.strip_prefix("generated/")?)
    }
}

#[cfg(all(test, unix))]
mod tests {
    use super::*;
    use crate::snapshot_capture::capture_sealed_source;
    use std::fs;
    use std::os::unix::fs::{PermissionsExt, symlink};

    fn capture(root: &std::path::Path) -> Arc<SealedSourceSnapshot> {
        Arc::new(
            capture_sealed_source(
                &[("generated".into(), root.to_path_buf())],
                false,
                2,
                100_000,
            )
            .unwrap(),
        )
    }

    #[test]
    fn retained_generated_bytes_modes_and_owner_survive_original_changes() {
        let root = tempfile::tempdir().unwrap();
        fs::create_dir(root.path().join("nested")).unwrap();
        fs::write(
            root.path().join("nested/generated.rs"),
            b"pub const VALUE: u8 = 42;\n",
        )
        .unwrap();
        fs::write(root.path().join("data.bin"), b"retained\0\xff").unwrap();
        fs::set_permissions(
            root.path().join("data.bin"),
            fs::Permissions::from_mode(0o700),
        )
        .unwrap();
        let image = capture(root.path());
        let source = GeneratedSource::from_snapshot(
            Arc::clone(&image),
            "generated",
            &["nested/generated.rs".into(), "data.bin".into()],
        )
        .unwrap();
        assert!(source.shares_snapshot(&image));
        assert!(!source.shares_snapshot(&capture(root.path())));
        fs::write(root.path().join("data.bin"), b"different bytes").unwrap();
        fs::write(root.path().join("new.rs"), b"new member").unwrap();
        assert_eq!(
            source.file_bytes("generated/data.bin"),
            Some(b"retained\0\xff".as_slice())
        );
        assert_eq!(source.files()[0].path, "generated/data.bin");
        assert!(source.files()[0].executable);
        assert!(!source.files()[1].executable);
        assert_eq!(source.directories(), &["nested"]);
        for path in [
            "data.bin",
            "generated/new.rs",
            "generated/../data.bin",
            "package/data.bin",
        ] {
            assert!(source.file_bytes(path).is_none(), "{path}");
        }
        let changed = GeneratedSource::from_snapshot(
            capture(root.path()),
            "generated",
            &[
                "nested/generated.rs".into(),
                "data.bin".into(),
                "new.rs".into(),
            ],
        )
        .unwrap();
        assert_ne!(
            SourceManifest::new(source.files().to_vec())
                .unwrap()
                .digest(),
            SourceManifest::new(changed.files().to_vec())
                .unwrap()
                .digest()
        );
    }

    #[test]
    fn empty_generated_tree_requires_a_real_captured_root() {
        let root = tempfile::tempdir().unwrap();
        let image = capture(root.path());
        let source = GeneratedSource::from_snapshot(Arc::clone(&image), "generated", &[]).unwrap();
        assert!(source.files().is_empty());
        assert!(source.directories().is_empty());
        assert!(source.shares_snapshot(&image));
        assert!(source.file_bytes("generated/anything").is_none());
        assert!(GeneratedSource::from_snapshot(image, "missing", &[]).is_err());
    }

    #[test]
    fn generated_tree_retains_empty_directories_without_sentinel_files() {
        let root = tempfile::tempdir().unwrap();
        fs::create_dir_all(root.path().join("empty/child")).unwrap();
        let only_directories =
            GeneratedSource::from_snapshot(capture(root.path()), "generated", &[]).unwrap();
        assert!(only_directories.files().is_empty());
        assert_eq!(only_directories.directories(), &["empty", "empty/child"]);
        fs::create_dir_all(root.path().join("nested/parent")).unwrap();
        fs::write(
            root.path().join("nested/parent/generated.rs"),
            b"generated source",
        )
        .unwrap();
        let paths = ["nested/parent/generated.rs".into()];
        let mixed =
            GeneratedSource::from_snapshot(capture(root.path()), "generated", &paths).unwrap();
        assert_eq!(mixed.files().len(), 1);
        assert_eq!(
            mixed.directories(),
            &["empty", "empty/child", "nested", "nested/parent"]
        );
        fs::write(
            root.path().join("empty/now-represented.rs"),
            b"another source",
        )
        .unwrap();
        let source = GeneratedSource::from_snapshot(
            capture(root.path()),
            "generated",
            &[
                "nested/parent/generated.rs".into(),
                "empty/now-represented.rs".into(),
            ],
        )
        .unwrap();
        assert_eq!(source.files().len(), 2);
        assert_eq!(source.directories(), mixed.directories());
        assert_eq!(only_directories.directories(), &["empty", "empty/child"]);
        assert!(
            mixed
                .file_bytes("generated/empty/now-represented.rs")
                .is_none()
        );
    }

    #[test]
    fn generated_directory_contract_refuses_aliases_missing_parents_and_unbounded_sets() {
        for paths in [
            vec![""],
            vec!["/absolute"],
            vec!["."],
            vec![".."],
            vec!["parent", "parent/../escape"],
            vec!["parent", "parent/./alias"],
            vec!["parent", "parent//child"],
            vec!["parent/child"],
            vec!["parent", "parent/child/grandchild"],
            vec!["trailing/"],
            vec!["back\\slash"],
            vec!["drive:directory"],
            vec!["control\nname"],
            vec!["same", "same"],
            vec!["z", "a"],
        ] {
            let directories: Vec<String> = paths.iter().map(|path| (*path).into()).collect();
            assert!(
                validate_generated_directories(&directories).is_err(),
                "{paths:?}"
            );
        }
        assert!(validate_generated_directories(&["a".repeat(1025)]).is_err());
        assert!(
            validate_generated_directories(&[std::iter::repeat_n("a", 33)
                .collect::<Vec<_>>()
                .join("/")])
            .is_err()
        );
        let excessive = (0..=MAX_GENERATED_DIRECTORIES)
            .map(|index| format!("directory-{index:05}"))
            .collect::<Vec<_>>();
        assert!(validate_generated_directories(&excessive).is_err());
        assert!(validate_generated_directories(&[]).is_ok());
        assert!(
            validate_generated_directories(&["a".into(), "a/b".into(), "a/b/c".into(), "z".into()])
                .is_ok()
        );
    }

    #[test]
    fn generated_projection_refuses_missing_extra_duplicate_and_nonregular_members() {
        let root = tempfile::tempdir().unwrap();
        fs::create_dir(root.path().join("nested")).unwrap();
        fs::write(root.path().join("one.rs"), b"one").unwrap();
        fs::write(root.path().join("two.rs"), b"two").unwrap();
        let image = capture(root.path());
        for paths in [
            vec![],
            vec!["one.rs"],
            vec!["one.rs", "one.rs", "two.rs"],
            vec!["one.rs", "two.rs", "extra.rs"],
            vec!["one.rs", "two.rs", "nested"],
            vec!["one.rs", "two.rs", "../one.rs"],
        ] {
            assert!(
                GeneratedSource::from_snapshot(
                    Arc::clone(&image),
                    "generated",
                    &paths.into_iter().map(str::to_owned).collect::<Vec<_>>()
                )
                .is_err()
            );
        }
        symlink("one.rs", root.path().join("alias.rs")).unwrap();
        assert!(
            GeneratedSource::from_snapshot(
                capture(root.path()),
                "generated",
                &["one.rs".into(), "two.rs".into()]
            )
            .is_err()
        );
    }
}

//! Acknowledged metadata delivery on the existing bounded installation lane.
//!
//! The core owns the complete destination reservation while this connection
//! replays one prefix. No metadata-store lock crosses the handshake. Session
//! cancellation signals the installer before joining it, including when an
//! async frame write/read is dropped. No detached writer survives this owner.

mod handshake;

use handshake::Exchange;
pub(super) use handshake::Identity;

use super::liveness::{OwnedWork, Permit, WorkError};
use super::rustc_request::{self, LiveEdge};
use super::{EdgeStream, FRAME_IO_BUDGET, read_frame, write_frame};
use crate::coord::live_dependency::{MAX_TRANSCRIPT_BYTES, PendingServe};
use serde_json::json;
use std::future::{Future, poll_fn};
use std::sync::Arc;
use std::task::Poll;
use std::time::Duration;

struct SessionWork {
    exchange: Arc<Exchange>,
    work: OwnedWork<String>,
}

impl Drop for SessionWork {
    fn drop(&mut self) {
        // OwnedWork's field drop joins. Wake its finite callback FIRST, even
        // if this session was cancelled inside an awaited socket operation.
        self.exchange.resolve(false);
    }
}

fn failure(error: impl std::fmt::Display) -> String {
    json!({
        "kind":"rustc-decision", "decision":"serve-failed",
        "reason":error.to_string(), "writer_returned":true,
        "compiler_skip_authorized":false,
    })
    .to_string()
}

fn terminal(reply: String, identity: &Identity, offered: bool) -> String {
    // These bytes are generated by the joined local installer, never supplied
    // by the peer. Bind its terminal suffix/refusal to the negotiated identity.
    let (mut value, exposed) = match serde_json::from_str::<serde_json::Value>(&reply) {
        Ok(value) if value.is_object() => (value, offered),
        _ => (
            json!({
                "kind":"rustc-decision", "decision":"serve-failed",
                "reason":"invalid local install answer", "writer_returned":true,
                "compiler_skip_authorized":false,
            }),
            true,
        ),
    };
    value["metadata_protocol"] = json!(1);
    value["action_key"] = json!(identity.action_key);
    value["manifest_key"] = json!(identity.manifest_key);
    if exposed {
        value["metadata_exposed"] = json!(true);
    }
    value.to_string()
}

enum Event {
    Prefix(Vec<u8>),
    Finished(Result<String, WorkError>),
}

pub(super) async fn install(
    permit: Permit,
    live: Arc<LiveEdge>,
    pending: Box<PendingServe>,
    metadata: Option<Identity>,
    stream: &mut EdgeStream,
) -> Option<String> {
    let Some(identity) = metadata else {
        return Some(
            match permit.finish(move || rustc_request::install(&live, pending)) {
                Ok(mut work) => work.wait().await.unwrap_or_else(failure),
                Err(error) => failure(error),
            },
        );
    };
    let exchange = Arc::new(Exchange::new(
        MAX_TRANSCRIPT_BYTES,
        FRAME_IO_BUDGET * 2 + Duration::from_secs(5),
    ));
    let callback = Arc::clone(&exchange);
    let acknowledged_identity = identity.clone();
    let work = match permit.finish(move || {
        rustc_request::install_with_metadata(&live, pending, |prefix| {
            callback.offer(prefix)?;
            // Record the real delivery boundary on the existing installation
            // thread, after the exact ACK and before bulk staging. Logging
            // must not delay the socket task's release of the callback.
            eprintln!(
                "{}",
                json!({
                    "kind":"rabsd-metadata-prefix-acknowledged",
                    "key":acknowledged_identity.action_key,
                    "manifest_key":acknowledged_identity.manifest_key,
                    "bytes":prefix.len(),
                    "sequence":1,
                })
            );
            Ok(())
        })
    }) {
        Ok(work) => work,
        Err(error) => return Some(terminal(failure(error), &identity, false)),
    };
    let mut session = SessionWork {
        exchange: Arc::clone(&exchange),
        work,
    };
    let mut completed = std::pin::pin!(session.work.wait());
    loop {
        let event = poll_fn(|cx| {
            if let Poll::Ready(Some(prefix)) = exchange.poll_prefix(cx) {
                return Poll::Ready(Event::Prefix(prefix));
            }
            completed.as_mut().poll(cx).map(Event::Finished)
        })
        .await;
        match event {
            Event::Prefix(prefix) => {
                let sent = write_frame(stream, &identity.notice(&prefix)).await;
                let acknowledged = sent
                    && read_frame(stream)
                        .await
                        .is_some_and(|frame| identity.acknowledges(&frame));
                exchange.resolve(acknowledged);
                if !acknowledged {
                    // Losing or rejecting the exact ACK is terminal. The
                    // owned installer returns before SessionWork can drop.
                    return None;
                }
            }
            Event::Finished(result) => {
                let (reply, exposed) = match result {
                    Ok(reply) => (reply, exchange.offered()),
                    // A joined task can panic after installing the head but
                    // before offering its transcript. Its returned writer
                    // does not prove that the destination stayed untouched.
                    Err(error) => (failure(error), true),
                };
                return Some(terminal(reply, &identity, exposed));
            }
        }
    }
}

#!/usr/bin/env python3
"""Real-worker preparation transactions on Linux; no network or actual npm.

Pass the compiled rch-wkr binary as the only argument. Test-owned managers
record actual argv and enforce the command independently specified by each
scenario. Cargo lifecycle tests use a recording executable, not a real Cargo
installation or the production shim. Fixtures are retained; teardown only
stops worker processes created here and releases the bounded test installers
it launched.
"""

import fcntl
import json
import os
from pathlib import Path
import select
import shutil
import signal
import subprocess
import sys
import tempfile
import time
import unittest

WORKER = str(Path(sys.argv.pop(1)).resolve()) if len(sys.argv) > 1 else None
IDLE = b"RCH_PREPARE_V1:idle\n"
RUNNING = b"RCH_PREPARE_V1:running\n"

NPM = r'''#!/bin/sh
set -eu
manager=${0##*/}
if [ "${1-}" = test ]; then
    if [ "${RCH_PREPARE_TEST_EXEC_TSC-}" = 1 ]; then
        exec tsc --noEmit
    fi
    if [ "${RCH_PREPARE_TEST_CARGO_LIFECYCLE-}" = 1 ]; then
        [ -f "$RCH_PREPARE_TEST_STATE/finished" ] || exit 95
        printf 'job\n' >> "$RCH_PREPARE_TEST_STATE/events"
    fi
    printf ran > "$RCH_PREPARE_TEST_STATE/user-command"
    exit 0
fi
# The worker pins npm's actual install root; validate that binding before
# recording the frozen/bootstrap plan shared by these transaction scenarios.
if [ "$manager" = npm ]; then
    [ "$#" -ge 3 ] && [ "$1" = --prefix ] && [ "$2" = "$PWD" ] || exit 97
    printf '%s' "$2" > "$RCH_PREPARE_TEST_STATE/npm-preparation-root"
    shift 2
fi
if [ "$manager" = pnpm ] && [ ! -e pnpm-workspace.yaml ]; then
    [ "$#" = 3 ] && [ "$3" = --ignore-workspace ] || exit 98
    printf '%s' "$PWD" > "$RCH_PREPARE_TEST_STATE/pnpm-preparation-root"
    set -- "$1" "$2"
fi
printf '%s\n' "$manager" "$#" "$@" >> "$RCH_PREPARE_TEST_STATE/argv"
printf '%s\n' "${PNPM_CONFIG_OPTIMISTIC_REPEAT_INSTALL-unset}" \
    "${pnpm_config_optimistic_repeat_install-unset}" "${PNPM_CONFIG_IGNORE_SCRIPTS-unset}" \
    > "$RCH_PREPARE_TEST_STATE/pnpm-environment"
[ "$manager" = "$RCH_PREPARE_EXPECT_MANAGER" ] || exit 93
case "$RCH_PREPARE_EXPECT_PLAN" in
    ci) [ "$#" = 1 ] && [ "$1" = ci ] || exit 90 ;;
    bootstrap) [ "$#" = 1 ] && [ "$1" = install ] || exit 90 ;;
    frozen) [ "$#" = 2 ] && [ "$1" = install ] && [ "$2" = --frozen-lockfile ] || exit 90 ;;
    *) exit 94 ;;
esac
printf 'install\n' >> "$RCH_PREPARE_TEST_STATE/events"
printf '%s\n' "$$" > "$RCH_PREPARE_TEST_STATE/started"
if [ "${RCH_PREPARE_TEST_CARGO_LIFECYCLE-}" = 1 ]; then
    printf '%s|%s\n' "${RCH_CARGO_WRAPPER_BYPASS-unset}" "${RCH_CARGO_WRAPPER_ORIGIN-unset}" > "$RCH_PREPARE_TEST_STATE/installer-env"
    cargo --version
    sh -c 'cargo build --features "native feature" --release'
fi
case "$RCH_PREPARE_TEST_MODE" in
    descendants)
        mkdir -p node_modules
        printf 'leader output\n' > node_modules/fixture-dependency
        # Even receipt-shaped installer output belongs only in the log.
        printf '{"version":1,"exit_code":0,"signal":null}\n'
        printf 'installer stderr before descendant completion\n' >&2
        printf '%s\n' "$PPID" > "$RCH_PREPARE_TEST_STATE/supervisor-pid"
        (
            printf ready > "$RCH_PREPARE_TEST_STATE/descendant-ready"
            n=0
            while [ ! -f "$RCH_PREPARE_TEST_STATE/release" ]; do
                n=$((n + 1))
                [ "$n" -lt 2000 ] || exit 91
                sleep 0.01
            done
            printf 'descendant output\n' > node_modules/fixture-dependency
            printf finished > "$RCH_PREPARE_TEST_STATE/descendant-finished"
        ) &
        printf '%s\n' "$!" > "$RCH_PREPARE_TEST_STATE/descendant-pid"
        n=0
        while [ ! -f "$RCH_PREPARE_TEST_STATE/release-leader" ]; do
            n=$((n + 1))
            [ "$n" -lt 2000 ] || exit 91
            sleep 0.01
        done
        exit "${RCH_PREPARE_TEST_LEADER_EXIT:-19}"
        ;;
    blocked)
        n=0
        while [ ! -f "$RCH_PREPARE_TEST_STATE/release" ]; do
            n=$((n + 1))
            [ "$n" -lt 2000 ] || exit 91
            sleep 0.01
        done
        ;;
    failure) exit 19 ;;
    timeout) exec sleep 30 ;;
    immediate) ;;
    *) exit 92 ;;
esac
mkdir -p node_modules
printf 'complete\n' > node_modules/fixture-dependency
if [ -n "${RCH_PREPARE_TEST_NEW_LOCK-}" ]; then
    printf 'generated by fixture\n' > "$RCH_PREPARE_TEST_NEW_LOCK"
fi
printf 'finished\n' > "$RCH_PREPARE_TEST_STATE/finished"
'''

# This test double records the real installer's environment and Cargo argv.
# Production Cargo shim authorization is covered by the rch shim tests.
CARGO = r'''#!/bin/sh
set -eu
printf '%s\0' "${RCH_CARGO_WRAPPER_BYPASS-unset}" "${RCH_CARGO_WRAPPER_ORIGIN-unset}" "$#" "$@" >> "$RCH_PREPARE_TEST_STATE/cargo"
if [ "${RCH_CARGO_WRAPPER_BYPASS-}" != 1 ] || [ "${RCH_CARGO_WRAPPER_ORIGIN-}" != rch ]; then
    printf 'fixture Cargo: missing managed environment\n' >&2
    exit 96
fi
case "${1-}" in
    --version) printf 'cargo 1.99.0 (fixture)\n' ;;
    build)
        printf 'fixture native build stdout\n'
        printf 'fixture native build stderr\n' >&2
        exit "${RCH_PREPARE_TEST_CARGO_EXIT:-0}"
        ;;
    *) exit 97 ;;
esac
'''


def eventually(predicate, message, timeout=6):
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if predicate():
            return
        time.sleep(0.01)
    raise AssertionError(message)


class PrepareTransactions(unittest.TestCase):
    def setUp(self):
        self.root = Path(tempfile.mkdtemp(prefix="rch-prepare-transactions-"))
        self.bin = self.root / "bin"
        self.home = self.root / "home"
        self.bin.mkdir()
        self.home.mkdir()
        self.children = []
        self.states = []
        # Never fall through to a machine's real manager, registry or user config.
        for name in ("sh", "mkdir", "sleep", "head", "od"):
            executable = shutil.which(name)
            self.assertIsNotNone(executable, name)
            (self.bin / name).symlink_to(executable)
        # Execute runs the real stdlib disk supervisor before preparation.
        # Keep the manager PATH isolated while providing only this interpreter.
        (self.bin / "python3").symlink_to(Path(sys.executable).resolve())
        for name in ("npm", "bun", "pnpm", "yarn"):
            manager = self.bin / name
            manager.write_text(NPM)
            manager.chmod(0o700)
        cargo = self.bin / "cargo"
        cargo.write_text(CARGO)
        cargo.chmod(0o700)
        tsc = self.bin / "tsc"
        tsc.write_text('#!/bin/sh\nprintf ran > "$RCH_PREPARE_TEST_STATE/user-command"\n')
        tsc.chmod(0o700)

    def tearDown(self):
        for state in self.states:
            (state / "release").write_bytes(b"release\n")
            (state / "release-leader").write_bytes(b"release\n")
        for child in self.children:
            try:
                child.communicate(timeout=5)
            except subprocess.TimeoutExpired:
                child.kill()
                child.communicate(timeout=5)

    def project(self, name, lock="package-lock.json"):
        project = self.root / name
        state = self.root / (name + "-state")
        project.mkdir()
        state.mkdir()
        (project / "package.json").write_text('{"name":"fixture","version":"1.0.0"}\n')
        if lock is not None:
            (project / lock).write_text('{"lockfileVersion":3}\n')
        self.states.append(state)
        return project, state

    def start(self, project, state, mode="immediate", execute=False,
              runtime="node", manager="npm", plan="ci", new_lock="",
              guarded=True, command=None, extra_env=None, prepare_options=()):
        user_command = command if command is not None else ("bun test" if runtime == "bun" else "tsc --noEmit")
        args = (["execute", "--workdir", str(project), "--command", user_command]
                if execute else ["prepare", "--project", str(project), "--runtime", runtime])
        if not execute:
            args.extend(prepare_options)
        if execute and guarded:
            # Fixture installers produce KiB, so test their actual transaction
            # outcomes with an explicit small budget independent of host GiB.
            args.extend(["--disk-budget-bytes", str(8 << 20),
                         "--disk-min-free-bytes", str(1 << 20)])
        env = {
            "PATH": str(self.bin), "HOME": str(self.home), "LC_ALL": "C",
            "XDG_CACHE_HOME": str(self.home / ".cache"),
            "XDG_CONFIG_HOME": str(self.home / ".config"),
            "XDG_STATE_HOME": str(self.home / ".local/state"),
            "TOKIO_WORKER_THREADS": "2", "RCH_PREPARE_INSTALL_TIMEOUT_SECS": "1" if mode == "timeout" else "20",
            "RCH_PREPARE_TEST_STATE": str(state), "RCH_PREPARE_TEST_MODE": mode,
            "RCH_PREPARE_EXPECT_MANAGER": manager, "RCH_PREPARE_EXPECT_PLAN": plan,
            "RCH_PREPARE_TEST_NEW_LOCK": new_lock,
        }
        if extra_env:
            env.update(extra_env)
        child = subprocess.Popen([WORKER, *args], env=env, stdin=subprocess.DEVNULL,
                                 stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        self.children.append(child)
        return child

    def report(self, child, expected_code):
        stdout, stderr = child.communicate(timeout=8)
        self.assertEqual(child.returncode, expected_code, (stdout, stderr))
        return json.loads(stdout)

    def journals(self):
        return sorted((self.home / ".cache/rch/prepare-transactions").glob("*.lock"))

    def events(self, state):
        path = state / "events"
        return path.read_text().splitlines() if path.exists() else []

    def invocations(self, state):
        path = state / "argv"
        return path.read_text().splitlines() if path.exists() else []

    def release_installer_leader(self, child, state):
        eventually(lambda: (state / "descendant-pid").exists()
                   and (state / "descendant-ready").exists(), "installer descendant did not start")
        leader = int((state / "started").read_text())
        supervisor = int((state / "supervisor-pid").read_text())
        descendant = int((state / "descendant-pid").read_text())
        group = os.getpgid(child.pid)
        self.assertEqual(os.getpgid(supervisor), group, "helper must remain inside the outer job group")
        self.assertEqual(os.getpgid(leader), group, "installer must remain inside the outer job group")
        self.assertEqual(os.getpgid(descendant), group, "lifecycle writer must remain inside the outer job group")
        # A kernel handle observes the exact live fixture, even when procfs
        # exposes a different PID namespace. Open it before releasing exit.
        descriptor = os.pidfd_open(leader)
        try:
            poller = select.poll()
            poller.register(descriptor, select.POLLIN)
            (state / "release-leader").write_text("release\n")
            self.assertTrue(poller.poll(3000), "installer leader did not exit")
        finally:
            os.close(descriptor)

    def test_installer_exit_waits_for_descendants_before_success_or_retry(self):
        for code in (0, 19):
            with self.subTest(installer_exit=code):
                project, state = self.project(f"descendant-{code}")
                previous_journals = set(self.journals())
                child = self.start(project, state, mode="descendants",
                                   extra_env={"RCH_PREPARE_TEST_LEADER_EXIT": str(code)})
                self.release_installer_leader(child, state)
                journal, = set(self.journals()) - previous_journals
                try:
                    with self.assertRaises(subprocess.TimeoutExpired,
                                           msg="foreground exit must not release a live dependency writer"):
                        child.communicate(timeout=0.2)
                    self.assertEqual(journal.read_bytes(), RUNNING)
                    self.assertFalse((project / ".rch_dep_fingerprint.json").exists())
                finally:
                    (state / "release").write_text("release\n")
                report = self.report(child, 0 if code == 0 else 1)
                self.assertEqual(report["action"], "Installed" if code == 0 else "Failed")
                self.assertTrue((state / "descendant-finished").is_file())
                dependency = project / "node_modules/fixture-dependency"
                self.assertEqual(dependency.read_text(), "descendant output\n")
                self.assertEqual(journal.read_bytes(), IDLE)
                log = Path(report["install_log_path"]).read_text()
                self.assertIn('{"version":1,"exit_code":0,"signal":null}', log)
                self.assertIn("installer stderr before descendant completion", log)
                if code != 0:
                    self.assertFalse((project / ".rch_dep_fingerprint.json").exists())
                    self.assertEqual(self.report(self.start(project, state), 0)["action"], "Installed")
                self.assertEqual(self.report(self.start(project, state), 0)["action"], "Skipped")
                self.assertEqual(dependency.read_text(), "descendant output\n" if code == 0 else "complete\n")

    def test_manager_rewrite_with_unchanged_path_invalidates_prepared_dependencies(self):
        project, state = self.project("manager-generation")
        first = self.report(self.start(project, state), 0)
        self.assertEqual(first["action"], "Installed")
        self.assertEqual(self.report(self.start(project, state), 0)["action"], "Skipped")
        manager = self.bin / "npm"
        metadata = manager.stat()
        # A same-path installer update used to preserve PATH/config/manifest
        # fingerprints. Restoring mtime also rules out an mtime-only fix.
        manager.write_text(NPM + "\nprintf upgraded > node_modules/manager-generation\n")
        os.utime(manager, ns=(metadata.st_atime_ns, metadata.st_mtime_ns))
        refreshed = self.report(self.start(project, state), 0)
        self.assertEqual(refreshed["action"], "Installed")
        self.assertNotEqual(refreshed["fingerprint"]["hash"], first["fingerprint"]["hash"])
        self.assertEqual(refreshed["fingerprint_changed_from"], first["fingerprint"]["hash"])
        self.assertEqual((project / "node_modules/manager-generation").read_text(), "upgraded")
        self.assertEqual(self.events(state), ["install", "install"])
        self.assertEqual(self.report(self.start(project, state), 0)["action"], "Skipped")

    def test_supervisor_crash_cannot_certify_a_failed_install(self):
        project, state = self.project("supervisor-crash")
        child = self.start(project, state, mode="descendants")
        eventually(lambda: (state / "descendant-ready").exists(), "installer descendant did not start")
        supervisor = int((state / "supervisor-pid").read_text())
        descriptor = os.pidfd_open(supervisor)
        try:
            signal.pidfd_send_signal(descriptor, signal.SIGKILL)
        finally:
            os.close(descriptor)
        self.assertEqual(self.report(child, 1)["action"], "Failed")
        journal, = self.journals()
        self.assertEqual(journal.read_bytes(), RUNNING, "no completion receipt means no settled transaction")
        self.assertFalse((project / ".rch_dep_fingerprint.json").exists())
        self.assertEqual(self.report(self.start(project, state), 1)["action"], "Failed")
        self.assertEqual(self.events(state), ["install"])
        (state / "release-leader").write_text("release\n")
        (state / "release").write_text("release\n")
        eventually(lambda: (state / "descendant-finished").exists(), "released fixture descendant did not finish")
        self.assertEqual(journal.read_bytes(), RUNNING)

    def test_descendant_timeout_retains_the_unconfirmed_transaction(self):
        project, state = self.project("descendant-timeout")
        child = self.start(project, state, mode="descendants", extra_env={
            "RCH_PREPARE_TEST_LEADER_EXIT": "0", "RCH_PREPARE_INSTALL_TIMEOUT_SECS": "1",
        })
        self.release_installer_leader(child, state)
        self.assertEqual(self.report(child, 2)["action"], "Timeout")
        journal, = self.journals()
        self.assertEqual(journal.read_bytes(), RUNNING)
        self.assertFalse((project / ".rch_dep_fingerprint.json").exists())
        self.assertEqual(self.report(self.start(project, state), 1)["action"], "Failed")
        self.assertEqual(self.events(state), ["install"])
        # Timeout has not claimed to kill descendants. Release this bounded
        # fixture explicitly and prove late completion cannot clear the fence.
        (state / "release").write_text("release\n")
        eventually(lambda: (state / "descendant-finished").exists(), "released fixture descendant did not finish")
        self.assertEqual(journal.read_bytes(), RUNNING)

    def test_install_timeout_stops_foreground_manager_and_retains_fence(self):
        project, state = self.project("foreground-timeout")
        child = self.start(project, state, mode="blocked",
                           extra_env={"RCH_PREPARE_INSTALL_TIMEOUT_SECS": "1"})
        eventually(lambda: (state / "started").exists(), "installer did not start")
        descriptor = os.pidfd_open(int((state / "started").read_text()))
        try:
            poller = select.poll()
            poller.register(descriptor, select.POLLIN)
            self.assertEqual(self.report(child, 2)["action"], "Timeout")
            self.assertTrue(poller.poll(3000), "timed-out foreground manager remained alive")
        finally:
            os.close(descriptor)
        journal, = self.journals()
        self.assertEqual(journal.read_bytes(), RUNNING)
        self.assertFalse((state / "finished").exists())
        self.assertFalse((project / ".rch_dep_fingerprint.json").exists())
        self.assertEqual(self.report(self.start(project, state), 1)["action"], "Failed")
        self.assertEqual(self.events(state), ["install"])

    def test_installer_exec_refuses_a_changed_supervisor_before_running_manager(self):
        _, state = self.project("wrong-supervisor")
        manager = self.bin / "launch-probe"
        manager.write_text('#!/bin/sh\nprintf ran > "$RCH_PREPARE_TEST_STATE/launcher-ran"\n')
        manager.chmod(0o700)
        result = subprocess.run(
            [WORKER, "prepare-installer", "--supervisor-pid", str(os.getppid()), "--", str(manager)],
            env={"PATH": str(self.bin), "RCH_PREPARE_TEST_STATE": str(state)},
            stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=5,
        )
        self.assertNotEqual(result.returncode, 0, (result.stdout, result.stderr))
        self.assertIn(b"installer supervisor is no longer the parent", result.stderr)
        self.assertFalse((state / "launcher-ran").exists())

    def test_bun_cache_miss_reports_install_outcomes_with_logs_and_fingerprints(self):
        # Moved from the ambient real-Bun unit smoke: this runs the real worker
        # and supervisor with deterministic managers and no registry access.
        for mode, code, action in [("immediate", 0, "Installed"), ("failure", 1, "Failed"),
                                   ("blocked", 2, "Timeout")]:
            with self.subTest(action=action):
                project, state = self.project(f"bun-cache-miss-{mode}", lock="bun.lockb")
                stamp = project / ".rch_dep_fingerprint.json"
                self.assertFalse(stamp.exists())
                report = self.report(self.start(project, state, mode=mode, runtime="bun",
                                                manager="bun", plan="frozen", extra_env={
                                                    "RCH_PREPARE_INSTALL_TIMEOUT_SECS": "1",
                                                }), code)
                self.assertEqual(report["action"], action)
                self.assertIsNotNone(report["fingerprint"])
                self.assertTrue(Path(report["install_log_path"]).is_file())
                self.assertEqual(self.invocations(state), ["bun", "2", "install", "--frozen-lockfile"])
                if action == "Installed":
                    self.assertTrue((project / "node_modules").is_dir())
                    self.assertEqual(json.loads(stamp.read_text())["hash"], report["fingerprint"]["hash"])
                else:
                    self.assertFalse(stamp.exists())

    def assert_cargo_lifecycle(self, project, state):
        self.assertEqual((state / "installer-env").read_text(), "1|rch\n")
        self.assertEqual((state / "cargo").read_bytes().split(b"\0"), [
            b"1", b"rch", b"1", b"--version",
            b"1", b"rch", b"4", b"build", b"--features", b"native feature", b"--release", b"",
        ])
        logs = list((project / ".rch_prepare_logs").glob("prepare_*.log"))
        self.assertEqual(len(logs), 1)
        self.assertEqual(logs[0].read_text(),
                         "cargo 1.99.0 (fixture)\nfixture native build stdout\nfixture native build stderr\n")

    def test_prepare_and_unguarded_execute_manage_installer_cargo_descendants(self):
        marker_cases = [
            ("absent", {}),
            ("unpaired", {"RCH_CARGO_WRAPPER_BYPASS": "1"}),
            ("conflicting", {"RCH_CARGO_WRAPPER_BYPASS": "0",
                             "RCH_CARGO_WRAPPER_ORIGIN": "caller", "RCH_REQUIRE_REMOTE": "1"}),
        ]
        for execute in (False, True):
            for name, markers in marker_cases:
                with self.subTest(execute=execute, markers=name):
                    project, state = self.project(f"lifecycle-{execute}-{name}")
                    env = {"RCH_PREPARE_TEST_CARGO_LIFECYCLE": "1", **markers}
                    # npm test needs worker preparation but has no automatic
                    # disk budget, so this reaches the plain executor path.
                    child = self.start(project, state, execute=execute, guarded=False,
                                       command="npm test", extra_env=env)
                    if execute:
                        stdout, stderr = child.communicate(timeout=8)
                        self.assertEqual(child.returncode, 0, (stdout, stderr))
                        self.assertEqual(stdout, b"", "installer output stays in its log")
                        self.assertEqual((state / "user-command").read_text(), "ran")
                    else:
                        self.assertEqual(self.report(child, 0)["action"], "Installed")
                        self.assertFalse((state / "user-command").exists())
                    self.assertFalse((project / ".rch-run").exists(), "no disk supervisor supplied the markers")
                    self.assertEqual(self.invocations(state), ["npm", "1", "ci"])
                    self.assertEqual(self.events(state), ["install", "job"] if execute else ["install"])
                    self.assert_cargo_lifecycle(project, state)

    def test_lifecycle_install_failure_never_launches_unguarded_job(self):
        for execute in (False, True):
            for failure in ("installer", "cargo"):
                with self.subTest(execute=execute, failure=failure):
                    project, state = self.project(f"lifecycle-failed-{execute}-{failure}")
                    env = {"RCH_PREPARE_TEST_CARGO_LIFECYCLE": "1", "RCH_CARGO_WRAPPER_BYPASS": "1",
                           "RCH_PREPARE_TEST_CARGO_EXIT": "101" if failure == "cargo" else "0"}
                    child = self.start(project, state, mode="failure" if failure == "installer" else "immediate",
                                       execute=execute, guarded=False, command="npm test", extra_env=env)
                    if execute:
                        stdout, stderr = child.communicate(timeout=8)
                        self.assertEqual(child.returncode, 121, (stdout, stderr))
                        self.assertIn(b"the command was not run", stderr)
                    else:
                        self.assertEqual(self.report(child, 1)["action"], "Failed")
                    self.assertFalse((state / "user-command").exists())
                    self.assertFalse((state / "finished").exists())
                    self.assertFalse((project / ".rch_dep_fingerprint.json").exists())
                    self.assertFalse((project / ".rch-run").exists())
                    self.assertEqual(self.invocations(state), ["npm", "1", "ci"])
                    self.assertEqual(self.events(state), ["install"])
                    self.assert_cargo_lifecycle(project, state)

    def test_npm_bootstrap_creates_a_lock_then_reuses_the_completed_install(self):
        project, state = self.project("npm-bootstrap", lock=None)
        original = (project / "package.json").read_bytes()
        report = self.report(self.start(project, state, plan="bootstrap",
                                        new_lock="package-lock.json"), 0)
        self.assertEqual(report["action"], "Installed")
        self.assertIn("package-lock.json", report["fingerprint"]["sources"])
        self.assertEqual((project / "package.json").read_bytes(), original)
        self.assertEqual(self.report(self.start(project, state), 0)["action"], "Skipped")
        self.assertEqual(self.invocations(state), ["npm", "1", "install"])

    def test_lock_selected_manager_is_preserved_across_runtime_hints(self):
        cases = [("package-lock.json", "npm", "ci"),
                 ("npm-shrinkwrap.json", "npm", "ci"),
                 ("bun.lock", "bun", "frozen"), ("bun.lockb", "bun", "frozen"),
                 ("pnpm-lock.yaml", "pnpm", "frozen"), ("yarn.lock", "yarn", "frozen")]
        for index, (lock, manager, plan) in enumerate(cases):
            for runtime in ("node", "bun"):
                with self.subTest(lock=lock, runtime=runtime):
                    project, state = self.project(f"manager-{index}-{runtime}", lock=lock)
                    original = (project / lock).read_bytes()
